// Only paints onto skin and the face, never onto a hat or hood; the vampire's eyes stay red.
const FACE_PIXELS = new Set(['w', 'a', 'k', 'q', 'e', 'f', 'r', 'j']);
export function faceRows32(rows, expr) {
  const out = rows.map(r => [...r]);
  const red = rows[15][14] === 'r';
  for (const [x, y, ch, free] of FACES32[expr]) {
    const was = out[y]?.[x];
    if (was === undefined) continue;
    if (free) { if (was === '.') out[y][x] = ch; continue; }
    if (!FACE_PIXELS.has(was)) continue;
    out[y][x] = ch === 'k' && red && y >= 11 && y <= 17 ? 'r' : ch;
  }
  return out.map(r => r.join(''));
}

// A 16px sprite at 32px: Scale2x rounds the steps off diagonal edges, then the outline, which came out two
// pixels thick, gets its inner half painted with the colour beside it.
export function up2(rows) {
  const h = rows.length, w = rows[0].length;
  const at = (x, y) => (x >= 0 && y >= 0 && x < w && y < h ? rows[y][x] : '.');
  const g = Array.from({ length: 2 * h }, () => Array(2 * w).fill('.'));
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const P = at(x, y), A = at(x, y - 1), B = at(x + 1, y), C = at(x - 1, y), D = at(x, y + 1);
    g[2 * y][2 * x] = C === A && C !== D && A !== B ? A : P;
    g[2 * y][2 * x + 1] = A === B && A !== C && B !== D ? B : P;
    g[2 * y + 1][2 * x] = D === C && D !== B && C !== A ? C : P;
    g[2 * y + 1][2 * x + 1] = B === D && B !== A && D !== C ? D : P;
  }
  const G = (x, y) => (x >= 0 && y >= 0 && x < 2 * w && y < 2 * h ? g[y][x] : '.');
  const N4 = [[1, 0], [-1, 0], [0, 1], [0, -1]], N8 = [...N4, [1, 1], [-1, -1], [1, -1], [-1, 1]];
  const edge = (x, y) => at(x, y) === 'k' && N4.some(([dx, dy]) => at(x + dx, y + dy) === '.');
  const out = g.map(r => [...r]);
  for (let y = 0; y < 2 * h; y++) for (let x = 0; x < 2 * w; x++) {
    if (g[y][x] !== 'k' || !edge(x >> 1, y >> 1) || N4.some(([dx, dy]) => G(x + dx, y + dy) === '.')) continue;
    for (const [dx, dy] of N8) { const c = G(x + dx, y + dy); if (c !== 'k' && c !== '.') { out[y][x] = c; break; } }
  }
  return out.map(r => r.join(''));
}
