// Round off the front of every hero's jaw: the cheek steps in one pixel before the chin,
// so the face reads as a soft bun instead of a box corner.
for (const name of Object.keys(SPR)) {
  if (!/^(adv|rogue|mage|knightP|vamp|hero_)/.test(name) || name === 'vampLord') continue;
  const rows = SPR[name], jaw = rows[10];
  if (jaw[13] !== 'k' && jaw[14] === 'k' && jaw[15] === '.') {
    SPR[name] = [...rows.slice(0, 10), jaw.slice(0, 13) + 'k..', ...rows.slice(11)];
  }
}
