// Relic and toolbar icons, 16x16 like everything else on the map.
// Each icon is drawn flat here, one letter per material, and shaded the same way for all of them:
// light from the upper left (a lit rim on that side of every part, a shaded rim on the lower right),
// then one dark outline around the whole shape. `fx` is laid on last, exactly as written: glints,
// engraving, sparks and glow (fx pixels outside the shape get no outline).

// material ramps: [lit, base, shade]
const RAMP = {
  l: ['w', 'l', 'L'], L: ['l', 'L', 'd'], d: ['L', 'd', 'x'],
  y: ['z', 'y', 'Y'], Y: ['y', 'Y', 'U'], i: ['z', 'i', 'u'], z: ['t', 'z', 'y'],
  o: ['y', 'o', 'O'], O: ['o', 'O', 'H'],
  r: ['q', 'r', 'R'], m: ['r', 'm', 'R'], R: ['m', 'R', 'x'],
  g: ['v', 'g', 'G'], G: ['g', 'G', 'X'], v: ['z', 'v', 'g'], 1: ['w', '1', '2'],
  b: ['c', 'b', 'B'], B: ['b', 'B', 'Z'], c: ['w', 'c', 'C'], C: ['c', 'C', 'B'],
  p: ['D', 'p', 'P'], P: ['p', 'P', 'Z'], D: ['A', 'D', 'p'],
  q: ['w', 'q', 'e'], e: ['q', 'e', 'j'],
  w: ['t', 'w', 'W'], a: ['t', 'a', 'W'],
  n: ['M', 'n', 'N'], N: ['n', 'N', 'H'], h: ['n', 'h', 'H'],
  s: ['I', 's', 'S'], J: ['I', 'J', 'M'],
  X: ['3', 'X', 'Z'], 3: ['D', '3', '4'],
};

function shade(rows) {
  const at = (x, y) => rows[y]?.[x] ?? '.';
  return rows.map((row, y) => [...row].map((c, x) => {
    const r = RAMP[c];
    if (!r) return c;
    const open = (dx, dy) => !r.includes(at(x + dx, y + dy));
    const lit = open(-1, 0) || open(0, -1), dark = open(1, 0) || open(0, 1);
    return lit && !dark ? r[0] : dark && !lit ? r[2] : c;
  }).join(''));
}

function outline(rows) {
  const solid = (x, y) => (rows[y]?.[x] ?? '.') !== '.';
  return rows.map((row, y) => [...row].map((c, x) => (c !== '.' ? c : solid(x - 1, y) || solid(x + 1, y) || solid(x, y - 1) || solid(x, y + 1) ? 'k' : '.')).join(''));
}

function make({ rows, fx }) {
  const out = outline(shade(rows));
  return fx ? out.map((row, y) => [...row].map((c, x) => (fx[y][x] !== '.' ? fx[y][x] : c)).join('')) : out;
}

