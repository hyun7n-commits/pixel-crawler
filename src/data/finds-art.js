// (and village life's, v0.30)
Object.assign(SHAPES, LIFE_SHAPES);

// a shape's rows with a find's materials put in, centred on a 16x16 tile
function fill(shape, pal) {
  const sh = SHAPES[shape], p0 = pal[0];
  const p1 = pal[1] || sh.d?.[0] || RAMP[p0]?.[2] || p0, p2 = pal[2] || sh.d?.[1] || 'k';
  const rows = sh.rows.map(r => r.replace(/ /g, '.').replace(/5/g, p0).replace(/6/g, p1).replace(/7/g, p2));
  const w = Math.max(...rows.map(r => r.length)), h = rows.length;
  const x0 = Math.floor((16 - w) / 2), y0 = Math.floor((16 - h) / 2) + (h < 12 ? 1 : 0);
  const out = [];
  for (let y = 0; y < 16; y++) {
    const r = rows[y - y0];
    out.push(r ? '.'.repeat(x0) + r.padEnd(w, '.') + '.'.repeat(16 - x0 - w) : '.'.repeat(16));
  }
  return out;
}

export const findIcon = (shape, pal) => make({ rows: fill(shape, pal) });
export const SHAPE_NAMES = Object.keys(SHAPES);
